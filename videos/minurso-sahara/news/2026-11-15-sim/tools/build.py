#!/usr/bin/env python3
"""Simulation of the reported operation (15 Nov 2026): schedule, sound effects, music, index.html.

One schedule drives everything: compositions/op.html reads window.SCHED (sched.js) for the
picture, and the audio clips in index.html are placed from the same numbers.

  python3 tools/build.py
"""
import json
import subprocess
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
MAIN = ROOT.parent.parent  # videos/minurso-sahara
SR = 44100
DUR = 32.0
rng = np.random.default_rng(20261115)

# ── schedule (seconds) ─────────────────────────────────────────────────────
S = {
    "duration": DUR,
    # camera: [start, duration, shot]
    "moves": [[0.5, 2.4, "over"], [8.6, 1.6, "north"], [16.8, 1.6, "south"], [26.0, 2.0, "over"]],
    "markers": {"ajbeil": 3.2, "tarf": 4.4, "gleibat": 5.6, "oum": 6.8},
    "batteries": 9.9,
    # shells: [launch, battery index, fraction along Tarf→Ajbeil, side offset (map units)]
    "shells": [[11.0, 0, 0.15, 2], [11.15, 1, 0.55, -3], [12.6, 0, 0.35, -2], [12.75, 1, 0.82, 3], [14.2, 0, 0.05, -1], [14.35, 1, 0.66, 2]],
    "flight": 1.15,
    # drones: enter, reach the loiter circle, release, impact
    "drones": [
        {"target": "gleibat", "enter": 17.5, "arrive": 20.1, "release": 21.4, "impact": 21.9},
        {"target": "oum", "enter": 18.3, "arrive": 20.9, "release": 23.0, "impact": 23.5},
    ],
    "phases": [0.0, 8.6, 16.8, 26.0],
}
(ROOT / "sched.js").write_text("// generated by tools/build.py\nwindow.SCHED = " + json.dumps(S, indent=1) + ";\n")


# ── sound effects ──────────────────────────────────────────────────────────
def write(name, x):
    x = x / (np.abs(x).max() + 1e-9) * 0.8
    with wave.open(str(ROOT / f"assets/sfx/{name}.wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((x * 32767).astype("<i2").tobytes())


def lowpass(x, a):
    y = np.zeros_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc += a * (v - acc)
        y[i] = acc
    return y


def t_(d):
    return np.arange(int(d * SR)) / SR


# artillery launch: a deep thump with a short blast of noise, mid content so it reads on a phone
t = t_(0.9)
f = 45 + 70 * np.exp(-t / 0.06)
body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.22)
blast = lowpass(rng.standard_normal(len(t)), 0.12) * np.exp(-t / 0.09) * 1.6
write("launch", body + blast)

# impact: a heavier, longer thud with crackle
t = t_(1.3)
f = 38 + 55 * np.exp(-t / 0.08)
body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.35)
crack = (rng.standard_normal(len(t)) - lowpass(rng.standard_normal(len(t)), 0.2)) * np.exp(-t / 0.05) * 0.5
rumble = lowpass(rng.standard_normal(len(t)), 0.03) * np.exp(-t / 0.5) * 2.0
write("impact", body + crack + rumble)

# drone: a propeller drone heard from afar (buzz with a slow wobble), 8 s
t = t_(8.0)
f0 = 118 * (1 + 0.012 * np.sin(2 * np.pi * 0.35 * t))
ph = 2 * np.pi * np.cumsum(f0) / SR
buzz = sum(np.sin(k * ph) / k ** 0.9 for k in range(1, 9))
air = lowpass(rng.standard_normal(len(t)), 0.25) * 0.25
env = np.minimum(1, t / 1.2) * np.clip((8.0 - t) / 1.5, 0, 1)
write("drone", (buzz * 0.5 + air) * env)

# missile: short falling whistle
t = t_(0.55)
f = 1400 - 900 * (t / 0.55)
write("missile", np.sin(2 * np.pi * np.cumsum(f) / SR) * np.minimum(1, t / 0.05) * np.clip((0.55 - t) / 0.1, 0, 1) * 0.6
      + lowpass(rng.standard_normal(len(t)), 0.3) * 0.15)

# ── music: the film's new theme, its tensest stretch (tanks + shield), 32 s ──
subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", "56.8", "-t", str(DUR), "-i", str(MAIN / "assets/music/bed-musique.m4a"),
                "-af", f"afade=t=in:d=0.4,afade=t=out:st={DUR - 2.2}:d=2.2", "-c:a", "aac", "-b:a", "192k",
                str(ROOT / "assets/music/bed.m4a")], check=True)


# ── index.html ──────────────────────────────────────────────────────────────
def wav_len(name):
    with wave.open(str(ROOT / f"assets/sfx/{name}.wav")) as w:
        return round(w.getnframes() / w.getframerate(), 3)


fx = []
for i, (t0, _, name) in enumerate(S["moves"]):
    fx.append((["whoosh-a", "whoosh-b", "whoosh-c", "whoosh-a"][i], t0, 0.45))
for k, t0 in S["markers"].items():
    fx.append(("click", t0, 0.45))
for t0, *_ in S["shells"]:
    fx.append(("launch", t0, 0.55))
    fx.append(("impact", round(t0 + S["flight"], 3), 0.7))
for d in S["drones"]:
    fx.append(("drone", d["enter"] - 0.3, 0.35))
    fx.append(("missile", d["release"], 0.4))
    fx.append(("impact", d["impact"], 0.75))
lanes, rows = [], []
for i, (name, t0, v) in enumerate(sorted(fx, key=lambda r: r[1])):
    d = wav_len(name)
    k = next((j for j, end in enumerate(lanes) if end <= t0), None)
    if k is None:
        lanes.append(0)
        k = len(lanes) - 1
    lanes[k] = t0 + d
    rows.append(f'      <audio id="sfx-{i:02d}-{name}" class="clip" src="assets/sfx/{name}.wav" data-start="{t0}" data-duration="{d}" data-volume="{v}" data-track-index="{20 + k}"></audio>')

(ROOT / "index.html").write_text(f"""<!doctype html>
<html lang="ar">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="vendor/gsap.min.js"></script>
    <script src="geo.js"></script>
    <script src="sched.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: #0D1316; }}
      #root {{ position: relative; width: 1080px; height: 1920px; overflow: hidden; background: #0D1316; }}
      .scene {{ position: absolute; inset: 0; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="1080" data-height="1920">
      <div id="op" class="scene" data-composition-id="op" data-composition-src="compositions/op.html"
        data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="graphics"></div>
      <audio id="music" class="clip" src="assets/music/bed.m4a" data-start="0" data-duration="{DUR}" data-volume="0.6" data-track-index="11"></audio>
{chr(10).join(rows)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
""")
print(f"sched.js, {len(rows)} sound clips on {len(lanes)} lanes, music {DUR}s")
