#!/usr/bin/env python3
"""SCRIPT-VO.md: the narration to record as a voice-over, every line with its start time in the video,
its window, and how to say numbers and Latin names. Run after tools/subtitles.py."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
S = json.loads((ROOT / "script.json").read_text())
C = json.loads((ROOT / "data/cues.json").read_text())
NAMES = {"s1": "شنو وقع", "s2": "الخريطة", "s3": "منين كيجي الضو للمحطتين", "s4": "الرواية الرسمية",
         "s5": "جوج جهات والخط المتأخر", "s6": "مدة الانقطاع", "s7": "باش ما يتعاودش", "s8": "أسئلة بلا جواب"}
SAY = {
    "s1a": "مساء الأربعاء، حداش نونبر ألفين وستة وعشرين، على الساعة ستّاش وتمنية وربعين دقيقة،",
    "s3a": "حسب «لو تروا سون سواسانت» نقلا عن مصدر مطلع، العاصفة أثرت على تغذية محطتي أولاد حدو ودار بوعزة.",
    "s3b": "بجوج محطات تحويل ميتين وخمسة وعشرين على عشرين كيلوفولط، ماشي محطات توليد.",
    "s3d": "حسب وثائق المكتب الوطني، بجوج معلقين على نفس الشريان ديال ميتين وخمسة وعشرين كيلوفولط،",
    "s4b": "والمكتب الوطني، حسب بلاغ نقلاتو «لو تروا سون سواسانت»، قال إن العاصفة أتلفات ربعة د الخطوط ديال ميتين وخمسة وعشرين كيلوفولط فنفس الوقت.",
    "s5c": "وكاين خط كان مبرمج باش يقوّي أولاد حدو: العوامر–أولاد حدو، ميتين وخمسة وعشرين كيلوفولط مزدوج، طولو تنين وتلاتين كيلومتر.",
}


def tc(x):
    m = int(x // 60)
    return f"{m}:{x - 60 * m:04.1f}"


out = [f"# سكريبت الـVO — «انقطاع الكهرباء بالدار البيضاء» ({tc(C['total'])[:4]})", "",
       "- **النبرة:** هادئة، بحال مذيع أخبار، سرعة عادية.",
       "- **التوقيت:** كل سطر كيبدا فالوقت المكتوب (الدقيقة:الثانية) فالفيديو، وعندو الوقت اللي بين قوسين.",
       "- **النطق:** فين كاين «نطق:» قرا داكشي اللي مكتوب، ماشي الأرقام.",
       "- **إلا بغيتي:** صيفط التسجيل (سطر بسطر، ولا تسجيل واحد بسكتة ثانية ونص بين كل سطر) ونوقّت الصورة على صوتك.", ""]
n = words = 0
for i, sc in enumerate(S["scenes"], 1):
    sid = sc["id"]
    st = C["scenes"][sid]["start"]
    out += [f"## المشهد {i} — {NAMES.get(sid, sid)}  ·  {tc(st)}", ""]
    for p in sc["phrases"]:
        n += 1
        a, b = C["scenes"][sid]["phrases"][p["id"]]
        words += len(p["text"].split())
        out += [f"**{n}.** `{tc(st + a)}` ({b - a:.1f} ث)  ", f"{p['text']}  "]
        if p["id"] in SAY:
            out.append(f"_نطق: {SAY[p['id']]}_  ")
        out.append("")
out.append(f"_{n} سطر، {words} كلمة. المصادر فآخر الفيديو؛ «شهادة» = ساكن من الدار البيضاء (رجوع الضو حتى 23:00)._")
(ROOT / "SCRIPT-VO.md").write_text("\n".join(out) + "\n")
print(n, words)
