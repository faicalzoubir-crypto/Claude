"""Writes index.html (the root composition) from the section table below.

Usage: python3 tools/build_index.py [--upto N]
  --upto N  only mount sections 1..N (section-by-section previews); default: all built sections.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# id, file, start, duration (seconds). Neighbouring sections overlap by the crossfade.
SECTIONS = [
    ("s1-hook", "compositions/s1-hook.html", 0.0, 3.0),
    ("s2-title", "compositions/s2-title.html", 3.0, 1.6),
    ("s3-material", "compositions/s3-material.html", 4.6, 3.6),
    ("s4-earth", "compositions/s4-earth.html", 8.2, 3.6),
    ("s5-prompt", "compositions/s5-prompt.html", 11.8, 7.0),
]
START = {sid: start for sid, _, start, _ in SECTIONS}

SFX_DUR = {"rewind.wav": 0.8, "whoosh.mp3": 0.57, "whoosh-short.mp3": 0.57, "pop.mp3": 0.72, "typing.mp3": 1.54,
           "key-press.mp3": 0.43, "ping.mp3": 1.32, "chime.mp3": 2.54, "click-soft.mp3": 0.36, "notification.mp3": 2.45}


def cues():
    """(file, absolute time, volume, optional duration) for every sound effect."""
    c = [("rewind.wav", 2.2, 0.9)]
    s3 = START["s3-material"]
    c.append(("whoosh.mp3", s3 + 0.15, 0.25))
    c += [("pop.mp3", s3 + 0.6 + k * 0.32, 0.22) for k in range(6)]
    c.append(("whoosh.mp3", START["s4-earth"] + 0.1, 0.25))
    s5 = START["s5-prompt"]
    c += [
        ("whoosh.mp3", s5 + 0.1, 0.25),
        ("typing.mp3", s5 + 0.4, 0.35, 0.9),
        ("key-press.mp3", s5 + 1.35, 0.4),
        ("ping.mp3", s5 + 1.45, 0.16),
        ("typing.mp3", s5 + 1.65, 0.35, 0.22),
        ("key-press.mp3", s5 + 1.9, 0.4),
        ("typing.mp3", s5 + 2.0, 0.35),
        ("typing.mp3", s5 + 3.54, 0.35, 0.36),
        ("whoosh-short.mp3", s5 + 4.3, 0.18),
    ]
    c += [("pop.mp3", s5 + 5.25 + k * 0.4, 0.18) for k in range(3)]
    return c
XFADE = 0.3

# The Vespa film's own music bed (assets/music/vespa-fond.wav) starts under the title,
# from the point where its groove begins, and fades out at the end.
MUSIC_FROM = 3.0
MUSIC_MEDIA_START = 12.0


def sfx_tags(total):
    out, lane_end = [], []
    for k, cue in enumerate(sorted(cues(), key=lambda c: c[1])):
        name, t, vol = cue[:3]
        if t >= total:
            continue
        d = round(min(cue[3] if len(cue) > 3 else SFX_DUR[name], total - t), 3)
        lane = next((i for i, e in enumerate(lane_end) if e <= t), None)
        if lane is None:
            lane_end.append(0)
            lane = len(lane_end) - 1
        lane_end[lane] = t + d + 0.01
        out.append(
            f'      <audio id="sfx-{k:02d}" src="assets/sfx/{name}" data-start="{round(t, 3)}" data-duration="{d}" data-track-index="{30 + lane}" data-volume="{vol}"></audio>'
        )
    return "\n".join(out)


def build(upto):
    secs = SECTIONS[:upto]
    total = round(secs[-1][2] + secs[-1][3], 3)
    hosts = []
    for k, (sid, src, start, dur) in enumerate(secs):
        hosts.append(
            f"""      <div
        id="el-{sid}"
        data-composition-id="{sid}"
        data-composition-src="{src}"
        data-start="{start}"
        data-duration="{dur}"
        data-track-index="{k + 1}"
        data-width="1080"
        data-height="1920"
      ></div>"""
        )
    music_dur = round(total - MUSIC_FROM, 3)
    automation = {
        "version": 1,
        "lanes": [
            {
                "target": "volume",
                "points": [
                    {"t": 0, "v": 0.0},
                    {"t": 0.4, "v": 0.85},
                    {"t": max(0.5, music_dur - 2.2), "v": 0.85},
                    {"t": music_dur, "v": 0.0},
                ],
            }
        ],
    }
    fades = "\n".join(
        f'      tl.fromTo("#el-{sid}", {{ opacity: 0 }}, {{ opacity: 1, duration: {XFADE}, ease: "power2.out" }}, {start});'
        for sid, _, start, _ in secs[1:]
    )
    html = f"""<!doctype html>
<html lang="fr">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="vendor/gsap.min.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: #0d1316; }}
      #root {{ position: relative; width: 100%; height: 100%; overflow: hidden; background: #0d1316; }}
      #root > div[data-composition-src] {{ position: absolute; inset: 0; }}
    </style>
  </head>
  <body>
    <!-- Making-of of the Vespa slide explainer. Generated by tools/build_index.py — edit the table there. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" data-fps="30" data-width="1080" data-height="1920">
{chr(10).join(hosts)}

{sfx_tags(total)}
      <audio
        id="music"
        src="assets/music/vespa-fond.wav"
        data-start="{MUSIC_FROM}"
        data-media-start="{MUSIC_MEDIA_START}"
        data-duration="{music_dur}"
        data-track-index="21"
        data-automation='{json.dumps(automation)}'
      ></audio>
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
{fades}
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
"""
    (ROOT / "index.html").write_text(html, encoding="utf-8")
    print(f"index.html · {len(secs)} section(s) · {total}s")


ap = argparse.ArgumentParser()
ap.add_argument("--upto", type=int, default=len(SECTIONS))
build(ap.parse_args().upto)
